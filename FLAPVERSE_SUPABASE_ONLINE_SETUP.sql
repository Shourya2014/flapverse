create extension if not exists pgcrypto;

create table if not exists public.fv_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  created_at timestamptz not null default now(),
  constraint fv_username_format check (username ~ '^[a-z0-9_]{3,20}$')
);

create table if not exists public.fv_player_state (
  user_id uuid primary key references auth.users(id) on delete cascade,
  state jsonb not null default '{}'::jsonb,
  total_pipes bigint not null default 0,
  deaths bigint not null default 0,
  coins_earned bigint not null default 0,
  favorite_world text,
  best_score integer not null default 0,
  achievement_count integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.fv_friends (
  id uuid primary key default gen_random_uuid(),
  requester uuid not null references auth.users(id) on delete cascade,
  addressee uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted')),
  created_at timestamptz not null default now(),
  constraint fv_no_self_friend check (requester <> addressee),
  constraint fv_friend_pair_unique unique (requester,addressee)
);

create table if not exists public.fv_challenges (
  id uuid primary key default gen_random_uuid(),
  sender uuid not null references auth.users(id) on delete cascade,
  receiver uuid not null references auth.users(id) on delete cascade,
  target_score integer not null default 1,
  status text not null default 'pending' check (status in ('pending','accepted','completed','declined')),
  sender_score integer not null default 0,
  receiver_score integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.fv_hall_of_fame (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  event_name text not null,
  winner_user_id uuid references auth.users(id) on delete set null,
  winner_username text not null,
  winning_score integer not null,
  badge text not null default '🏆',
  won_at timestamptz not null default now()
);

alter table public.fv_profiles enable row level security;
