-- Secure Hall-of-Fame claim for the current 7-day Golden Pass event.
create or replace function public.fv_claim_golden_pass_event()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  w record;
begin
  if auth.uid() is null then
    return jsonb_build_object('won',false,'reason','login_required');
  end if;

  if now() < timestamptz '2026-09-02 00:00:00+05:30' then
    return jsonb_build_object('won',false,'reason','event_not_ended');
  end if;

  select player_id, username, best_score
  into w
  from public.flapverse_leaderboard
  order by best_score desc, updated_at asc
  limit 1;

  if w.player_id is null or coalesce(w.best_score,0) <= 990 then
    return jsonb_build_object('won',false,'reason','no_qualifying_winner');
  end if;

  if w.player_id <> auth.uid()::text then
    return jsonb_build_object('won',false,'reason','not_winner');
  end if;

  insert into public.fv_hall_of_fame
    (event_key,event_name,winner_user_id,winner_username,winning_score,badge,won_at)
  values
    ('golden-pass-aug-2026','7-DAY GOLDEN PASS CHALLENGE',auth.uid(),w.username,w.best_score,'👑',now())
  on conflict (event_key) do nothing;

  return jsonb_build_object('won',true,'username',w.username,'score',w.best_score);
end;
$$;

grant execute on function public.fv_claim_golden_pass_event() to authenticated;
